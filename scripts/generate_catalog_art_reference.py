"""Refresh the Flutter fallback's reference data from a Kalinka backend checkout.

Run with the backend's Python environment (Pillow and NumPy are required):
  /path/to/backend/.venv/bin/python scripts/generate_catalog_art_reference.py /path/to/backend
Then dart format lib/utils/catalog_casefold.dart.
"""

import importlib.util
import json
from dataclasses import asdict
from pathlib import Path
import sys
import unicodedata

root = Path(__file__).resolve().parents[1]
backend = Path(sys.argv[1]).resolve()
spec = importlib.util.spec_from_file_location(
    "catalog_art_render",
    backend / "packages/kalinka-server/src/kalinka_server/catalog_art_render.py",
)
art = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = art
spec.loader.exec_module(art)

# Full case folding is locale independent, unlike lowercasing. Compact regular
# runs into ranges; keep expansions and irregular mappings as exceptions.
folds = {
    code: chr(code).casefold()
    for code in range(0x110000)
    if chr(code).casefold() != chr(code)
}
remaining = dict(folds)
ranges = []
for code, folded in folds.items():
    if code not in remaining or len(folded) != 1:
        continue
    delta = ord(folded) - code
    best = []
    for step in (1, 2):
        run = []
        current = code
        while remaining.get(current) == chr(current + delta):
            run.append(current)
            current += step
        if len(run) > len(best):
            best = run
    if len(best) >= 3:
        ranges.append((best[0], best[-1], best[1] - best[0], delta))
        for current in best:
            del remaining[current]

lines = [
    "// Generated by scripts/generate_catalog_art_reference.py.",
    f"// Python Unicode {unicodedata.unidata_version}; matches the backend's str.casefold().",
    "String catalogCaseFold(String text) {",
    "  final result = StringBuffer();",
    "  for (final rune in text.runes) {",
    "    final special = _exceptions[rune];",
    "    if (special != null) {",
    "      result.write(special);",
    "      continue;",
    "    }",
    "    var folded = rune;",
    "    for (final (start, end, step, delta) in _ranges) {",
    "      if (rune >= start && rune <= end && (rune - start) % step == 0) {",
    "        folded += delta;",
    "        break;",
    "      }",
    "    }",
    "    result.writeCharCode(folded);",
    "  }",
    "  return result.toString();",
    "}",
    "",
    "const _ranges = [",
    *(f"  ({a}, {b}, {step}, {delta})," for a, b, step, delta in ranges),
    "];",
    "",
    "const _exceptions = <int, String>{",
]
for code, folded in remaining.items():
    escaped = "".join(f"\\u{{{ord(c):x}}}" for c in folded)
    lines.append(f"  {code}: '{escaped}',")
lines.append("};\n")
(root / "lib/utils/catalog_casefold.dart").write_text("\n".join(lines))

fixtures = root / "test/fixtures/catalog_art"
fixtures.mkdir(parents=True, exist_ok=True)
titles = [
    "Home",
    "Explore",
    "Genres",
    "Moods",
    "My Mixes",
    "My Collection",
    "Jazz",
    "Albums",
    "Artists",
    "Tracks",
    "Folders",
    "Recently Added",
    "Singles & loose tracks",
    "Rock",
    "Classical",
    "Pop",
    "Electronic",
    "Soul",
    "Blues",
    "Folk",
    "Hip Hop",
    "Dance",
    "Country",
    "Latin",
    "  JAZZ\t",
    "Straße",
    "STRASSE",
    "Café",
    "Cafe\u0301",
    "ＪＡＺＺ",
    "Σίσυφος",
    "ΣΊΣΥΦΟΣ",
    "İstanbul",
    "Музыка",
    "ᎠᏣᎳᎩ",
    "🎵 Music",
    "A\u0085B",
    "A\ufeffB",
    "A\x00B",
    " A\u001cB ",
    "".join(chr(code) for code in folds),
]
inputs = [(title, "", "test:catalog") for title in titles]
inputs.extend(
    [
        ("Jazz", "Updated description", "other:catalog"),
        (" ", " Albums ", "test:catalog"),
        ("", "", "test:catalog"),
        ("\t", "\u0085", "other:catalog"),
    ]
)
cases = []
seen = {geometry: set() for geometry in range(len(art.BACKGROUND_DESIGNS))}
for title, description, entity_id in inputs:
    key = art.background_text_key((title, description), entity_id)
    geometry = int(key[:16], 16) % len(art.BACKGROUND_DESIGNS)
    accent, highlight = art._background_colors(key)
    transform = art.background_transform(key)
    case = dict(
        title=title,
        description=description,
        entityId=entity_id,
        textKey=key,
        geometry=geometry,
        palette=int(key[16:32], 16) % len(art.BACKGROUND_PALETTES),
        accent=accent,
        highlight=highlight,
        transform=asdict(transform),
        affine=transform.affine(2400, 800),
        tones=[
            art._tint_background(art.Image.new("L", (1, 1), g), key).getpixel((0, 0))
            for g in range(256)
        ],
    )
    if len(seen[geometry]) < 3 and transform not in seen[geometry]:
        seen[geometry].add(transform)
        name = art.BACKGROUND_DESIGNS[geometry]
        if len(seen[geometry]) > 1:
            name += f"-{len(seen[geometry])}"
        case["image"] = name
        art._background(360, 120, key).save(fixtures / f"{name}-card.png")
        art._background(120, 120, key, text_column=False).save(
            fixtures / f"{name}-thumb.png"
        )
    cases.append(case)
assert all(len(transforms) >= 2 for transforms in seen.values())
(fixtures / "reference.json").write_text(
    json.dumps(
        dict(style=art.STYLE_VERSION, unicode=unicodedata.unidata_version, cases=cases),
        ensure_ascii=False,
        separators=(",", ":"),
    )
    + "\n"
)
print(
    f"Wrote {len(cases)} seed/LUT/transform cases, "
    f"{sum(map(len, seen.values()))} card/thumbnail pairs, and Unicode case folding."
)
